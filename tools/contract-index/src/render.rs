use crate::clauses::{Clause, Definitions};
use crate::tags::{Artifact, Tagged};

pub(crate) const START_MARKER: &str = "<!-- contract-index:start -->";
pub(crate) const END_MARKER: &str = "<!-- contract-index:end -->";

pub(crate) fn evidence_index(definitions: &Definitions, tagged: &Tagged) -> String {
    let mut clauses: Vec<&Clause> = definitions.clauses.iter().collect();
    clauses.sort_by_cached_key(|clause| sort_key(&clause.id));
    let proofs = clauses
        .iter()
        .filter(|clause| {
            tagged
                .get(&clause.id)
                .is_some_and(|artifacts| artifacts.iter().any(|item| item.kind.is_proof()))
        })
        .count();
    let gaps = clauses.len() - proofs;
    let mut out = String::new();
    out.push_str("# Contract evidence index\n\n");
    out.push_str(
        "Generated by `contract-index`. Do not edit; regenerate with `cargo run --locked -p contract-index`.\n\n",
    );
    out.push_str(&format!(
        "{} clauses, {proofs} with proof artifacts, {gaps} gaps.\n\n",
        clauses.len()
    ));
    out.push_str("| Clause | Defined in | Tagged artifacts | Gap |\n");
    out.push_str("| :--- | :--- | :--- | :--- |\n");
    for clause in clauses {
        let (rendered, gap) = artifact_cell(tagged, &clause.id);
        let file = file_name(&clause.file);
        out.push_str(&format!(
            "| `{}` | [{file}]({file}) | {rendered} | {gap} |\n",
            clause.id
        ));
    }
    out
}

fn artifact_cell(tagged: &Tagged, id: &str) -> (String, &'static str) {
    let mut artifacts: Vec<Artifact> = tagged.get(id).cloned().unwrap_or_default();
    artifacts.sort();
    artifacts.dedup();
    let proof = artifacts.iter().any(|item| item.kind.is_proof());
    if artifacts.is_empty() {
        return ("none".to_string(), "gap");
    }
    let rendered = artifacts
        .iter()
        .map(render_artifact)
        .collect::<Vec<_>>()
        .join("<br>");
    (rendered, if proof { "" } else { "gap" })
}

fn render_artifact(artifact: &Artifact) -> String {
    let path = &artifact.path;
    let item = artifact.item.replace('|', "\\|");
    let kind = artifact.kind.label();
    format!("`{path}`::{item} ({kind})")
}

pub(crate) fn readme_block(definitions: &Definitions) -> String {
    let mut lines = Vec::new();
    for file in &definitions.files {
        let clauses: Vec<&Clause> = definitions
            .clauses
            .iter()
            .filter(|clause| &clause.file == file)
            .collect();
        lines.push(readme_line(file_name(file), &clauses));
    }
    let joined = lines.join("\n");
    format!("{joined}\n")
}

fn readme_line(file: &str, clauses: &[&Clause]) -> String {
    if clauses.is_empty() {
        return format!("- [{file}]({file}): no clause IDs.");
    }
    let families: Vec<String> = families(clauses).iter().map(render_family).collect();
    let list = families.join(", ");
    format!("- [{file}]({file}): {list}.")
}

fn file_name(file: &str) -> &str {
    file.rsplit('/').next().unwrap_or(file)
}

struct Family {
    prefix: String,
    members: Vec<Member>,
}

struct Member {
    number: u64,
    suffix: String,
    id: String,
}

fn families(clauses: &[&Clause]) -> Vec<Family> {
    let mut families: Vec<Family> = Vec::new();
    for clause in clauses {
        let member = member_of(&clause.id);
        match families
            .iter_mut()
            .find(|family| family.prefix == clauses_prefix(&clause.id))
        {
            Some(family) => family.members.push(member),
            None => families.push(Family {
                prefix: clauses_prefix(&clause.id).to_string(),
                members: vec![member],
            }),
        }
    }
    for family in &mut families {
        family
            .members
            .sort_by(|left, right| (left.number, &left.suffix).cmp(&(right.number, &right.suffix)));
    }
    families
}

fn clauses_prefix(id: &str) -> &str {
    id.rsplit_once('-').map_or("", |(prefix, _)| prefix)
}

fn member_of(id: &str) -> Member {
    let last = id.rsplit_once('-').map_or(id, |(_, last)| last);
    let digits = last.chars().take_while(char::is_ascii_digit).count();
    Member {
        number: last[..digits].parse().unwrap_or(0),
        suffix: last[digits..].to_string(),
        id: id.to_string(),
    }
}

fn render_family(family: &Family) -> String {
    let mut rendered = Vec::new();
    let mut index = 0;
    while index < family.members.len() {
        let member = &family.members[index];
        if !member.suffix.is_empty() {
            rendered.push(format!("`{}`", member.id));
            index += 1;
            continue;
        }
        let mut end = index;
        while end + 1 < family.members.len()
            && family.members[end].suffix.is_empty()
            && family.members[end + 1].suffix.is_empty()
            && family.members[end + 1].number == family.members[end].number + 1
        {
            end += 1;
        }
        if end > index {
            rendered.push(format!(
                "`{}`–`{}`",
                family.members[index].id, family.members[end].id
            ));
        } else {
            rendered.push(format!("`{}`", member.id));
        }
        index = end + 1;
    }
    rendered.join(", ")
}

fn sort_key(id: &str) -> (String, u64, String) {
    let member = member_of(id);
    (clauses_prefix(id).to_string(), member.number, member.suffix)
}

pub(crate) fn splice_readme(existing: &str, block: &str) -> Result<String, String> {
    let start = existing
        .find(START_MARKER)
        .ok_or_else(|| format!("docs/contracts/README.md has no {START_MARKER}"))?;
    let end_offset = existing[start..]
        .find(END_MARKER)
        .ok_or_else(|| format!("docs/contracts/README.md has no {END_MARKER}"))?;
    let end = start + end_offset + END_MARKER.len();
    let mut out = String::with_capacity(existing.len() + block.len());
    out.push_str(&existing[..start]);
    out.push_str(START_MARKER);
    out.push('\n');
    out.push_str(block);
    out.push_str(END_MARKER);
    out.push_str(&existing[end..]);
    Ok(out)
}

#[expect(clippy::expect_used, reason = "test assertions")]
#[cfg(test)]
mod tests {
    use super::{evidence_index, readme_block, splice_readme};
    use crate::clauses::{Clause, Definitions};
    use crate::tags::{Artifact, Kind, Tagged};

    fn clause(id: &str) -> Clause {
        Clause {
            id: id.to_string(),
            file: "demo.md".to_string(),
        }
    }

    #[test]
    fn readme_ranges_keep_suffixed_ids_and_gaps() {
        let mut definitions = Definitions {
            files: vec!["demo.md".to_string()],
            ..Definitions::default()
        };
        for id in ["ARCH-01", "ARCH-02", "ARCH-03", "ARCH-04"] {
            definitions.clauses.push(clause(id));
        }
        definitions.clauses.push(clause("ARCH-04a"));
        definitions.clauses.push(clause("CONV-1"));
        let block = readme_block(&definitions);
        assert_eq!(
            block,
            "- [demo.md](demo.md): `ARCH-01`–`ARCH-04`, `ARCH-04a`, `CONV-1`.\n"
        );
    }

    #[test]
    fn index_marks_gap_rows_and_reports_proofs() {
        let mut definitions = Definitions::default();
        definitions.clauses.push(clause("DEMO-01"));
        definitions.clauses.push(clause("DEMO-02"));
        let mut tagged = Tagged::new();
        tagged.insert(
            "DEMO-01".to_string(),
            vec![Artifact {
                path: "crates/demo/src/lib.rs".to_string(),
                item: "proves_it".to_string(),
                kind: Kind::Test,
            }],
        );
        tagged.insert(
            "DEMO-02".to_string(),
            vec![Artifact {
                path: "crates/demo/src/lib.rs".to_string(),
                item: "helper".to_string(),
                kind: Kind::Owner,
            }],
        );
        let index = evidence_index(&definitions, &tagged);
        assert!(
            index.contains("2 clauses, 1 with proof artifacts, 1 gaps."),
            "{index}"
        );
        assert!(
            index.contains(
                "| `DEMO-01` | [demo.md](demo.md) | `crates/demo/src/lib.rs`::proves_it (test) |  |"
            ),
            "{index}"
        );
        assert!(index.contains("| `DEMO-02` | [demo.md](demo.md) | `crates/demo/src/lib.rs`::helper (owner) | gap |"), "{index}");
    }

    #[test]
    fn splice_replaces_only_the_marked_block() {
        let existing = "# Contracts\n<!-- contract-index:start -->\n- old\n<!-- contract-index:end -->\nTail.\n";
        let spliced = splice_readme(existing, "- new\n").expect("splice");
        assert_eq!(
            spliced,
            "# Contracts\n<!-- contract-index:start -->\n- new\n<!-- contract-index:end -->\nTail.\n"
        );
    }
}
