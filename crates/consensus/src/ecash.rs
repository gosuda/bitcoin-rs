//! ecash betanet repurpose-forgiveness data.
//!
//! The ecash fork repurposed 232 historical mainnet transaction outputs into
//! the betanet genesis supply (upstream `setRepurposeTx`, `validation.cpp`).
//! Betanet shares mainnet's full history, so those txids still sit in the
//! UTXO set, but their real input scripts never replay against betanet's
//! state: consensus skips input-script verification for exactly these txids
//! while every other check (finality, outpoints, amounts, sigops) still
//! applies. Mainnet, testnet, signet, and regtest keep verifying them
//! normally - the skip is gated on the [`VerifyFlags::ECASH`] activation
//! carried by `verify_flags` for networks with an ecash fork.
//!
//! Byte convention: the entries are the txids' raw little-endian consensus
//! encodings - the same internal layout as Core's `uint256` - sorted
//! lexicographically, which is exactly `std::set<uint256>`'s memcmp order.
//! `Txid::from_str` parses the same display hex Core's `uint256("...")`
//! constructor takes, so round-tripping a display hex through
//! `Txid::from_str(..).as_bytes()` reproduces these entries byte for byte.

