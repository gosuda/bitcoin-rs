/// Returns whether `txid`'s raw little-endian encoding is one of the 232
/// repurposed mainnet txids whose input scripts betanet no longer verifies.
#[must_use]
pub fn is_repurpose_txid(txid: &[u8; 32]) -> bool {
    REPURPOSE_TXIDS.binary_search(txid).is_ok()
}

#[cfg(test)]
mod tests {
    use std::str::FromStr;

    use bitcoin_rs_primitives::Txid;

    use super::{REPURPOSE_TXIDS, is_repurpose_txid};

    /// Display-order hex of the first entry in Core's `std::set` ordering.
    const FIRST_DISPLAY_HEX: &str =
        "1e16a31a1e27267b0b8e1bd5857ce2a00f58dd6503394954dd9389aef56e3100";
    /// Display-order hex of the last entry in Core's `std::set` ordering.
    const LAST_DISPLAY_HEX: &str =
        "791f369a6267ce4d28227375c3d2e13c774ff39a90219b7100c4329359bbeeff";

    #[test]
    fn set_is_sorted_unique_and_exactly_232() {
        assert_eq!(REPURPOSE_TXIDS.len(), 232);
        for pair in REPURPOSE_TXIDS.windows(2) {
            assert!(pair[0] < pair[1], "entries must be strictly ascending");
        }
    }

    #[test]
    fn display_hex_round_trips_into_stored_little_endian_bytes() {
        // Pins the byte convention: Core's uint256("hex") and this crate's
        // Txid::from_str both parse display-order hex into little-endian
        // internal bytes, so the stored arrays are those parse results.
        let first = Txid::from_str(FIRST_DISPLAY_HEX)
            .unwrap_or_else(|error| panic!("fixture txid hex parses: {error}"));
        let last = Txid::from_str(LAST_DISPLAY_HEX)
            .unwrap_or_else(|error| panic!("fixture txid hex parses: {error}"));
        assert_eq!(first.as_bytes(), &REPURPOSE_TXIDS[0]);
        assert_eq!(last.as_bytes(), &REPURPOSE_TXIDS[231]);
        assert_eq!(first.to_string(), FIRST_DISPLAY_HEX);
    }

    #[test]
    fn lookup_hits_members_and_misses_foreign_hashes() {
        assert!(is_repurpose_txid(&REPURPOSE_TXIDS[0]));
        assert!(is_repurpose_txid(&REPURPOSE_TXIDS[115]));
        assert!(is_repurpose_txid(&REPURPOSE_TXIDS[231]));
        let miss = [0xab_u8; 32];
        assert!(!is_repurpose_txid(&miss));
        // A one-bit flip of a member must miss.
        let mut flipped = REPURPOSE_TXIDS[0];
        flipped[0] ^= 0x01;
        assert!(!is_repurpose_txid(&flipped));
    }
}
